const catalogs = { en, 'zh-Hans': zhHans } as const;

export function t(
  locale: AppLocale,
  key: keyof typeof en,
  variables: Readonly<Record<string, string | number>> = {},
): string {
  return Object.entries(variables).reduce(
    (value, [name, replacement]) =>
      value.replaceAll(`{${name}}`, String(replacement)),
    catalogs[locale][key],
  );
}
